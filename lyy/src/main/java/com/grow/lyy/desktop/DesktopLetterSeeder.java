package com.grow.lyy.desktop;

import lombok.RequiredArgsConstructor;
import lombok.extern.slf4j.Slf4j;
import org.springframework.boot.ApplicationArguments;
import org.springframework.boot.ApplicationRunner;
import org.springframework.context.annotation.Profile;
import org.springframework.core.io.ClassPathResource;
import org.springframework.jdbc.datasource.init.DatabasePopulatorUtils;
import org.springframework.jdbc.datasource.init.ResourceDatabasePopulator;
import org.springframework.stereotype.Component;

import javax.sql.DataSource;

/**
 * Loads private hidden letters that are not already present in the local
 * database. Existing rows are left untouched, so edits made through the local
 * letter manager survive restarts. The seed is generated by
 * desktop/prepare-letters.ps1 and is never committed to git.
 */
@Slf4j
@Component
@Profile("desktop")
@RequiredArgsConstructor
public class DesktopLetterSeeder implements ApplicationRunner {

    private final DataSource dataSource;

    @Override
    public void run(ApplicationArguments args) {
        ClassPathResource seed = new ClassPathResource("db/desktop/letters.sql");
        if (!seed.exists()) {
            log.info("未找到桌面版隐藏信件 seed，跳过。");
            return;
        }

        ResourceDatabasePopulator populator = new ResourceDatabasePopulator(seed);
        populator.setSqlScriptEncoding("UTF-8");
        DatabasePopulatorUtils.execute(populator, dataSource);
        log.info("桌面版隐藏信件 seed 已载入。");
    }
}
